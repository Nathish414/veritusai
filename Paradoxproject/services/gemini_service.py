import os
import time
import logging
from dotenv import load_dotenv
from google import genai
from google.genai import errors

load_dotenv()

logger = logging.getLogger(__name__)

class GeminiConfigError(Exception):
    """Raised when the Gemini API configuration is missing or invalid."""
    pass

class GeminiAPIError(Exception):
    """Raised when upstream Gemini API communication fails."""
    pass

TRANSIENT_HTTP_CODES = {429, 500, 502, 503, 504}
TRANSIENT_STATUS_STRINGS = {"UNAVAILABLE", "RESOURCE_EXHAUSTED", "INTERNAL", "DEADLINE_EXCEEDED"}

def is_transient_gemini_error(exc: Exception) -> bool:
    """
    Determine if a Gemini exception represents a transient failure eligible for retry.
    Transient errors include: 503 (Service Unavailable), 500 (Internal), 429 (Rate Limit / Quota),
    and network connection / timeout exceptions.
    Non-retryable errors include: 400 (Bad Request / Invalid Key), 401 (Unauthenticated), 403 (Permission Denied), 404 (Not Found).
    """
    if isinstance(exc, errors.APIError):
        code = getattr(exc, "code", None)
        status = getattr(exc, "status", None)

        # Permanent client errors - never retry
        if code in {400, 401, 403, 404}:
            return False

        if code in TRANSIENT_HTTP_CODES:
            return True

        if status in TRANSIENT_STATUS_STRINGS:
            return True

        msg = str(exc).lower()
        if "api_key_invalid" in msg or "invalid api key" in msg or "permission_denied" in msg or "not found" in msg:
            return False

        if any(term in msg for term in ["503", "unavailable", "overloaded", "resource_exhausted", "rate limit", "timeout", "reset by peer"]):
            return True

        return False

    # Connection / Socket / Timeout exceptions are transient
    exc_type = type(exc).__name__.lower()
    transient_types = ["timeout", "connecterror", "connectionerror", "readtimeout", "remote_disconnected"]
    if any(t in exc_type for t in transient_types):
        return True

    return False

def generate_ai_response(prompt: str, model: str = None, max_retries: int = 3, base_delay: float = 1.0) -> str:
    """
    Generate an AI text response using the official google-genai SDK.
    Uses ONLY the configured model (default: 'gemini-3.8-flash' or GEMINI_MODEL env var).
    Retries transient server errors (503, 500, 429) up to max_retries with exponential backoff.
    Fails fast without retry on permanent errors (400, 401, 403, 404).

    Args:
        prompt: Non-empty prompt string to send to Gemini.
        model: Optional model override. If None, reads GEMINI_MODEL env var (default: 'gemini-3.8-flash').
        max_retries: Maximum number of attempts for transient errors (default: 3).
        base_delay: Initial delay in seconds for exponential backoff (default: 1.0s).

    Returns:
        str: Clean text generated by the model.

    Raises:
        GeminiConfigError: When GEMINI_API_KEY is not set or empty.
        GeminiAPIError: When the Gemini API call fails upstream after retrying.
    """
    api_key = os.getenv("GEMINI_API_KEY")
    if not api_key or not api_key.strip():
        logger.error("Gemini API key is missing from environment variables.")
        raise GeminiConfigError("GEMINI_API_KEY is not configured.")

    # Use strictly the configured model. No hardcoded fallback model chains.
    target_model = model or os.getenv("GEMINI_MODEL", "gemini-3.8-flash")
    if not target_model or not target_model.strip():
        target_model = "gemini-3.8-flash"
    target_model = target_model.strip()

    client = None
    last_error = None

    try:
        client = genai.Client(api_key=api_key.strip())

        attempt = 0
        while attempt < max_retries:
            attempt += 1
            try:
                logger.info(f"Calling Gemini API with model: {target_model} (attempt {attempt}/{max_retries})")
                response = client.models.generate_content(
                    model=target_model,
                    contents=prompt
                )

                if response and response.text:
                    return response.text.strip()
                elif response and hasattr(response, "candidates") and response.candidates:
                    first_candidate = response.candidates[0]
                    if hasattr(first_candidate, "content") and first_candidate.content:
                        parts = getattr(first_candidate.content, "parts", [])
                        text = "".join([getattr(p, "text", "") for p in parts])
                        if text:
                            return text.strip()
                return ""

            except errors.APIError as api_err:
                last_error = api_err
                code = getattr(api_err, "code", None)
                status = getattr(api_err, "status", None)

                # 1. Non-retryable permanent error (400, 401, 403, 404)
                if not is_transient_gemini_error(api_err):
                    logger.error(f"Gemini API permanent error ({code or status}) for model '{target_model}': {type(api_err).__name__}")
                    if code == 404:
                        raise GeminiAPIError(f"The configured model '{target_model}' was not found or is unavailable.") from api_err
                    elif code in {401, 403}:
                        raise GeminiAPIError("Authentication or permission error communicating with Gemini API.") from api_err
                    else:
                        raise GeminiAPIError(f"Gemini API rejected request ({code or status or 'Bad Request'}).") from api_err

                # 2. Transient error (503, 500, 429) -> retry with exponential backoff
                if attempt < max_retries:
                    delay = base_delay * (2 ** (attempt - 1))
                    logger.warning(
                        f"Transient Gemini API error ({code or status}) on attempt {attempt}/{max_retries} for model '{target_model}'. "
                        f"Retrying in {delay:.1f}s with exponential backoff..."
                    )
                    time.sleep(delay)
                    continue
                else:
                    logger.error(
                        f"Gemini API transient error ({code or status}) for model '{target_model}' persisted after {max_retries} attempts."
                    )
                    raise GeminiAPIError(
                        f"The Gemini AI service is temporarily unavailable ({code or status or 'Service Overloaded'}). Please try again shortly."
                    ) from api_err

            except Exception as ex:
                last_error = ex
                if not is_transient_gemini_error(ex):
                    logger.error(f"Non-retryable error invoking Gemini model '{target_model}': {type(ex).__name__}")
                    raise GeminiAPIError("An error occurred while communicating with the AI service.") from ex

                # Transient connection error
                if attempt < max_retries:
                    delay = base_delay * (2 ** (attempt - 1))
                    logger.warning(
                        f"Transient network error ({type(ex).__name__}) on attempt {attempt}/{max_retries}. "
                        f"Retrying in {delay:.1f}s..."
                    )
                    time.sleep(delay)
                    continue
                else:
                    logger.error(f"Connection error persisted after {max_retries} attempts: {type(ex).__name__}")
                    raise GeminiAPIError("Connection to AI service timed out after multiple retry attempts.") from ex

        # Fallback if loop exited unexpectedly
        raise GeminiAPIError("Failed to obtain response from Gemini API.") from last_error

    finally:
        if client:
            try:
                client.close()
            except Exception:
                pass
